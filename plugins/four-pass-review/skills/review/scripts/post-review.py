# --------------------------------------------------------------------------
# Previous runs
# --------------------------------------------------------------------------
#
# Re-reviewing is the normal case: review, push fixes, review again. Without
# this the PR collects a new review and a duplicate set of inline comments
# every time. GitHub will not let a submitted review be deleted, so "replace"
# means supersede: blank the old review's body, drop its inline comments, then
# post the new one. A `--mode summary` comment is an issue comment, which can
# be edited in place, so that case is a true update.

SUPERSEDED_NOTE = "_Superseded by a newer four-pass review._"


def find_prior_reviews(reviews: list[dict], login: str,
                       include_superseded: bool = False) -> list[dict]:
    """Reviews this tool posted as `login`: our footer, and ours to edit.

    `login` is required, not optional. Superseding deletes inline comments,
    which cannot be undone, so a review is only ever a candidate when we can
    prove whose it is. Matching on the footer alone would mean that a failed
    `gh api user` call is enough to start deleting another account's comments.
    """
    out = []
    for r in reviews:
        body = r.get("body") or ""
        if FOOTER not in body:
            continue
        if SUPERSEDED_NOTE in body and not include_superseded:
            continue
        if (r.get("user") or {}).get("login") != login:
            continue
        out.append(r)
    return out


def find_prior_comment(comments: list[dict], login: str) -> dict | None:
    """The most recent issue comment this tool posted as `login`, if any."""
    ours = [c for c in comments
            if FOOTER in (c.get("body") or "")
            and (c.get("user") or {}).get("login") == login]
    return ours[-1] if ours else None


def unknown_login_warning(action: str) -> str:
    return (f"could not confirm the authenticated account (`gh api user` failed); "
            f"not {action} an earlier review. Leaving a duplicate is better than "
            f"editing or deleting something we cannot prove is ours.")


def stale_comment_ids(review_comments: list[dict], review_ids: set[int]) -> list[int]:
    """Inline comments belonging to the given reviews."""
    return [c["id"] for c in review_comments
            if c.get("pull_request_review_id") in review_ids and "id" in c]


def gh(*args: str, input_text: str | None = None) -> str:
    proc = subprocess.run(["gh", *args], input=input_text, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"gh {' '.join(args)} failed ({proc.returncode}):\n{proc.stderr.strip()}")
    return proc.stdout


def pr_info(pr: str, repo: str | None,
            require_open: bool = True) -> tuple[str, str, str]:
    """Return (owner/repo, head sha, html url)."""
    args = ["pr", "view", pr, "--json", "headRefOid,url,state"]
    if repo:
        args += ["--repo", repo]
    data = json.loads(gh(*args))
    if require_open and data.get("state", "OPEN") != "OPEN":
        raise RuntimeError(f"PR {pr} is {data.get('state')}; refusing to post a review")
    url = data["url"]
    m = re.match(r"https?://[^/]+/([^/]+/[^/]+)/pull/\d+", url)
    owner_repo = repo or (m.group(1) if m else None)
    if not owner_repo:
        raise RuntimeError(f"could not determine owner/repo from {url}; pass --repo")
    return owner_repo, data["headRefOid"], url


def pr_diff(pr: str, repo: str | None) -> str:
    args = ["pr", "diff", pr]
    if repo:
        args += ["--repo", repo]
    return gh(*args)


def post_review(owner_repo: str, pr: str, payload: dict) -> dict:
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as tmp:
        json.dump(payload, tmp)
        tmp_path = tmp.name
    try:
        out = gh("api", "--method", "POST", f"repos/{owner_repo}/pulls/{pr}/reviews",
                 "--input", tmp_path)
    finally:
        os.unlink(tmp_path)
    return json.loads(out)


def post_review_with_fallbacks(owner_repo: str, pr: str, payload: dict, findings: list[dict],
                              summary: str, head_sha: str) -> dict:
    """Post the review, degrading when GitHub refuses the event or an anchor."""
    for _ in range(3):
        try:
            return post_review(owner_repo, pr, payload)
        except RuntimeError as e:
            text = str(e)
            if SELF_REVIEW_MARKER in text.lower() and payload["event"] != DEFAULT_EVENT:
                print(f"GitHub refused a {payload['event']} review on your own PR; "
                      f"posting the same review as a {DEFAULT_EVENT}", file=sys.stderr)
                payload["event"] = DEFAULT_EVENT
                continue
            if "422" in text and payload["comments"]:
                # GitHub rejected an anchor we thought was valid; post everything
                # in the body. An empty diff map makes every finding unanchored.
                print(f"inline anchoring rejected ({text}); retrying as body-only review",
                      file=sys.stderr)
                payload, _ = build_review(findings, summary, {}, head_sha,
                                          heading=FALLBACK_HEADING, event=payload["event"])
                continue
            raise
    raise RuntimeError("gave up posting the review after retrying")


def gh_json(*args: str):
    """A `gh api` call whose output is JSON. Returns [] when the call fails."""
    try:
        return json.loads(gh(*args) or "[]")
    except (RuntimeError, json.JSONDecodeError) as e:
        print(f"could not read {args[-1]}: {e}", file=sys.stderr)
        return []


def current_login() -> str | None:
    """The authenticated user, used to avoid touching someone else's review."""
    try:
        return gh("api", "user", "--jq", ".login").strip() or None
    except RuntimeError:
        return None


def supersede_reviews(owner_repo: str, pr: str, reviews: list[dict]) -> None:
    """Blank out earlier reviews from this tool and delete their inline comments.

    Best effort throughout: a PR we cannot tidy is still a PR we should post
    the new review to, so every failure here warns and continues.
    """
    by_id = {r["id"]: r for r in reviews if "id" in r}
    if not by_id:
        return
    comments = gh_json("api", "--paginate", f"repos/{owner_repo}/pulls/{pr}/comments")
    for comment_id in stale_comment_ids(comments, set(by_id)):
        try:
            gh("api", "--method", "DELETE",
               f"repos/{owner_repo}/pulls/comments/{comment_id}")
        except RuntimeError as e:
            print(f"could not delete stale comment {comment_id}: {e}", file=sys.stderr)
    for review_id in sorted(by_id):
        # Keep the `reviewed at <sha>` marker: it is how a later run works out
        # what has already been covered. Blanking it would make every
        # re-review start from scratch.
        old_body = by_id[review_id].get("body") or ""
        m = REVIEWED_RE.search(old_body)
        try:
            gh("api", "--method", "PUT",
               f"repos/{owner_repo}/pulls/{pr}/reviews/{review_id}",
               "-f", f"body={SUPERSEDED_NOTE}\n\n{footer_line(m.group(1) if m else None)}")
        except RuntimeError as e:
            print(f"could not supersede review {review_id}: {e}", file=sys.stderr)


def update_summary_comment(owner_repo: str, comment_id: int, body: str) -> str:
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as tmp:
        json.dump({"body": body}, tmp)
        tmp_path = tmp.name
    try:
        out = gh("api", "--method", "PATCH",
                 f"repos/{owner_repo}/issues/comments/{comment_id}", "--input", tmp_path)
    finally:
        os.unlink(tmp_path)
    return json.loads(out).get("html_url", "")


def post_summary_comment(pr: str, repo: str | None, body: str) -> str:
    with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False) as tmp:
        tmp.write(body)
        tmp_path = tmp.name
    try:
        args = ["pr", "comment", pr, "--body-file", tmp_path]
        if repo:
            args += ["--repo", repo]
        return gh(*args).strip()
    finally:
        os.unlink(tmp_path)


