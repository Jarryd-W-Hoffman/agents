def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pr", required=True, help="pull request number")
    ap.add_argument("--findings", help="path to findings.json")
    ap.add_argument("--summary", help="path to summary.md (review body)")
    ap.add_argument("--mode", choices=["inline", "summary"], default="inline")
    ap.add_argument("--verdict", choices=sorted(VERDICT_EVENTS),
                    help="override the verdict; by default it is read from summary.md")
    ap.add_argument("--repo", help="owner/repo override")
    ap.add_argument("--on-existing", choices=["replace", "skip", "add"], default="replace",
                    help="what to do when this tool already reviewed this PR "
                         "(default: replace, which supersedes the earlier review)")
    ap.add_argument("--diff-file", help="read the diff from a file instead of `gh pr diff` "
                                        "(with --head-sha, makes --dry-run work offline)")
    ap.add_argument("--head-sha", help="head commit for --diff-file dry runs")
    ap.add_argument("--last-reviewed", action="store_true",
                    help="print the head sha this tool last reviewed on this PR "
                         "and exit; exits 1 with no output when there is none")
    ap.add_argument("--dry-run", action="store_true", help="print payload, post nothing")
    args = ap.parse_args(argv)
    if not args.last_reviewed and not (args.findings and args.summary):
        ap.error("--findings and --summary are required unless --last-reviewed is given")

    if args.last_reviewed:
        owner_repo, _, _ = pr_info(args.pr, args.repo, require_open=False)
        login = current_login()
        if login is None:
            print(unknown_login_warning("reading"), file=sys.stderr)
            return 1
        sha = last_reviewed_sha(
            gh_json("api", "--paginate", f"repos/{owner_repo}/pulls/{args.pr}/reviews"),
            login)
        if not sha:
            print(f"no earlier four-pass review found on PR {args.pr}", file=sys.stderr)
            return 1
        print(sha)
        return 0

    with open(args.findings, encoding="utf-8") as fh:
        findings = json.load(fh)
    # Refuse before anything reaches GitHub: a finding with no body or a
    # severity off the scale would post as a broken comment, in public.
    errors = validate_findings(findings)
    if errors:
        for e in errors:
            print(f"findings.json: {e}", file=sys.stderr)
        print("findings.json breaks the finding contract (finding.schema.json); "
              "nothing posted", file=sys.stderr)
        return 2
    with open(args.summary, encoding="utf-8") as fh:
        summary = fh.read()

    verdict = args.verdict or verdict_from_summary(summary)
    event = event_for_verdict(verdict)

    # A dry run against a saved diff touches no network, so the documented
    # "dry-run first" step works offline and in tests.
    offline = bool(args.dry_run and args.diff_file and args.head_sha)
    if offline:
        owner_repo, head_sha, url = (args.repo or "OWNER/REPO"), args.head_sha, "(offline)"
    else:
        # Both modes refuse to post to a PR that is not open.
        owner_repo, head_sha, url = pr_info(args.pr, args.repo)

    if args.mode == "summary":
        body = build_summary_body(findings, summary, head_sha)
        prior_comment = None
        if not offline and args.on_existing != "add":
            login = current_login()
            if login is None:
                print(unknown_login_warning("updating"), file=sys.stderr)
            else:
                comments = gh_json("api", "--paginate",
                                   f"repos/{owner_repo}/issues/{args.pr}/comments")
                prior_comment = find_prior_comment(comments, login)
        if prior_comment and args.on_existing == "skip":
            print(f"already commented: "
                  f"{prior_comment.get('html_url', prior_comment.get('id'))}; "
                  "nothing posted (--on-existing skip)", file=sys.stderr)
            return 0
        if args.dry_run:
            if prior_comment:
                print(f"would update comment {prior_comment.get('id')}", file=sys.stderr)
            print(body)
            return 0
        if prior_comment:
            print(update_summary_comment(owner_repo, prior_comment["id"], body))
            return 0
        print(post_summary_comment(args.pr, args.repo, body))
        return 0

    if args.diff_file:
        with open(args.diff_file, encoding="utf-8") as fh:
            diff_text = fh.read()
    else:
        diff_text = pr_diff(args.pr, args.repo)
    diff_files = parse_diff(diff_text)
    payload, unanchored = build_review(findings, summary, diff_files, head_sha, event=event)

    prior_reviews: list[dict] = []
    if not offline and args.on_existing != "add":
        login = current_login()
        if login is None:
            print(unknown_login_warning("superseding"), file=sys.stderr)
        else:
            prior_reviews = find_prior_reviews(
                gh_json("api", "--paginate",
                        f"repos/{owner_repo}/pulls/{args.pr}/reviews"), login)

    print(f"PR: {url} @ {head_sha[:10]}", file=sys.stderr)
    print(f"verdict: {verdict or 'unknown'} -> review event {event}", file=sys.stderr)
    print(f"inline comments: {len(payload['comments'])}; in body only: {len(unanchored)}",
          file=sys.stderr)
    for f in unanchored:
        print(f"  not anchorable: [{f['id']}] {f['path']}:{f['line']}", file=sys.stderr)
    if prior_reviews:
        ids = ", ".join(str(r.get("id")) for r in prior_reviews)
        print(f"earlier reviews from this tool: {ids} ({args.on_existing})", file=sys.stderr)

    if prior_reviews and args.on_existing == "skip":
        print("nothing posted (--on-existing skip)", file=sys.stderr)
        return 0

    if args.dry_run:
        print(json.dumps(payload, indent=2))
        return 0

    if prior_reviews:
        supersede_reviews(owner_repo, args.pr, prior_reviews)

    result = post_review_with_fallbacks(owner_repo, args.pr, payload, findings,
                                        summary, head_sha)
    print(result.get("html_url", url))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (RuntimeError, ValueError, OSError, json.JSONDecodeError) as exc:
        print(f"post-review: {exc}", file=sys.stderr)
        sys.exit(1)
